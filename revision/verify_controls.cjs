const { runControls, startControls, expect, assert } = require('./controls_harness.cjs');
const { readFile } = require('node:fs/promises');

runControls(async (page, base) => {
  const { go, button, row, action } = await startControls(page, base);
  const download = async (locator, id) => {
    const [file] = await Promise.all([page.waitForEvent('download'), locator.click()]);
    assert.ok(file.suggestedFilename().startsWith(id + '_') && file.suggestedFilename().endsWith('_demo.txt'));
    const content = await readFile(await file.path(), 'utf8');
    assert.ok(content.includes(id) && content.includes('sin validez legal ni tributaria'));
  };
  const orderId = 'PV-264716';
  await go('/pedidos');
  await page.locator('#pd-q').fill(orderId);
  await action(orderId, 'Ver en el flujo');
  await expect(page.locator('h1')).toHaveText('Flujo de ' + orderId);
  await expect(page.locator('#fl-main')).toContainText(await page.evaluate((id) => LFX.findOrder(id).estado, orderId));
  await expect(page.locator('#pv-save')).toHaveCount(0);
  await go('/pedidos');
  await page.locator('#pd-q').fill(orderId);
  const original = await page.evaluate((id) => LFX.findOrder(id).lineas, orderId);
  await action(orderId, 'Duplicar pedido');
  await expect(page.locator('#fl-side h2').first()).toContainText('BOR-');
  const copyURL = page.url();
  const copyClient = await page.evaluate((id) => LFX.findOrder(id).clienteNombre, orderId);
  await expect(page.locator('#fl-side')).toContainText(copyClient);
  assert.deepEqual(await page.locator('[data-qi]').evaluateAll((inputs) => inputs.map((i) => +i.value)), original.map((l) => l.cant));
  await page.locator('[data-rm]').first().click();
  assert.deepEqual(await page.evaluate((id) => LFX.findOrder(id).lineas, orderId), original);
  await go('/pedidos');
  await page.getByRole('link', { name: 'Nuevo pedido', exact: true }).click();
  await expect(page.locator('#pv-save')).toBeDisabled();
  assert.notEqual(page.url(), copyURL);
  const client = await page.evaluate(() => LFX.data.clientes.find((c) => c.nombre === 'Minimarket El Roble'));
  await go('/clientes/' + client.id);
  await page.getByRole('link', { name: 'Nuevo pedido', exact: true }).click();
  await expect(page.locator('#fl-side')).toContainText(client.nombre);
  await expect(page.locator('[data-qi]')).toHaveCount(0);
  await page.goto(copyURL);
  await expect(page.locator('[data-qi]')).toHaveCount(original.length - 1);
  await go('/recepcion');
  await action('OC-88403', 'Ver comparativo');
  await expect(page.locator('#rc-cmp')).toContainText('OC-88403');
  await expect(page.locator('main')).toContainText('Solo consulta');
  await expect(page.locator('#rc')).toHaveCount(0);
  const openOC = await page.evaluate(() => LFX.data.ocs.find((o) => o.id !== 'OC-88412' && o.estado !== 'Cerrada').id);
  await go('/recepcion');
  await action(openOC, 'Recepcionar');
  await expect(page.locator('#rc-cmp')).toContainText(openOC);
  await page.locator('#rc-sim').click();
  await page.locator('#rc-q').fill('13');
  await page.locator('#rc button[type=submit]').click();
  await expect(page.getByRole('dialog')).toContainText(openOC);
  await button('Siguiente pallet').click();
  await expect(page.locator('#rc-cmp')).toContainText('13 u');
  await go('/recepcion/nueva?oc=' + openOC + '&modo=consulta');
  await expect(page.locator('#rc-cmp')).toContainText('13 u');
  await go('/pedidos/' + orderId);
  await download(page.locator('[data-doc]').first(), orderId);
  await go('/portal/proveedor');
  await page.locator('#pv-dev').click();
  const nc = page.locator('[data-nc]').first();
  await download(nc, await nc.getAttribute('data-nc'));
  await go('/portal/transportista');
  await page.locator('#tp-docs').click();
  const dl = page.locator('[data-dl]').first();
  await download(dl, await dl.getAttribute('data-dl'));
  await go('/clientes');
  await page.locator('#cl-new').click();
  await page.locator('#nc-rut').fill('12.345.678-5');
  await button('Crear solicitud').click();
  await expect(page.locator('#cl-requests')).toContainText('SOL-CLI-0001');
  await page.locator('#cl-new').click();
  await page.locator('#nc-rut').fill('123456785');
  await button('Crear solicitud').click();
  await expect(page.getByRole('dialog')).toContainText('Ya hay una solicitud para este RUT');
  await page.keyboard.press('Escape');
  await go('/canal-moderno');
  await page.locator('#cm-new').click();
  await page.locator('#nc-n').fill('Cadena QA');
  await page.locator('#nc-s').selectOption({ index: 1 });
  await page.locator('#nc-m0').fill('');
  await button('Activar cadena').click();
  await expect(page.getByRole('dialog')).toContainText('Este campo es obligatorio');
  await page.locator('#nc-m0').fill('QA-MAPEO');
  await button('Activar cadena').click();
  await page.locator('#edi-chains summary').click();
  await expect(page.locator('#edi-chains')).toContainText('QA-MAPEO');
  await expect(page.locator('#edi-net')).toContainText('4 cadenas configuradas');
  await go('/preparacion');
  await expect(page.locator('[data-mission="M-3301"]')).toContainText('Solo consulta');
  const before = await page.locator('[data-mission]').count();
  await page.locator('#pp-gen').click();
  const added = await page.locator('[data-mission]').count();
  assert.ok(added > before, 'La generación agrega misiones nuevas; antes: ' + before + ', después: ' + added + ', avisos: ' + await page.locator('#toasts').innerText());
  await page.locator('#pp-gen').click();
  await expect(page.locator('[data-mission]')).toHaveCount(added);
  const mission = page.locator('[data-mission]').nth(before);
  const missionId = await mission.getAttribute('data-mission');
  const missionOrder = await page.evaluate((id) => LFX.prepMissions().find((m) => m.id === id).pedido.id, missionId);
  await mission.getByRole('link', { name: 'Iniciar misión' }).click();
  await expect(page.locator('#fl-side h2').first()).toContainText(missionOrder);
  await expect(page.locator('main')).toContainText('Escenario de práctica: preparación · ' + missionId);
}, 'E-01 a E-04, E-06 y E-08')
  .catch((error) => { console.error(error); process.exitCode = 1; });
