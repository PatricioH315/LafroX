def esc(s):
    return s.replace("%", "\\%").replace("&", "\\&")

def main(out):
    tot = Counter()
    lines = []
    for titulo, pref, filas in GRUPOS:
        cnt = Counter(f[1] for f in filas)
        tot.update(cnt)
        lines.append("\\Needspace{8\\baselineskip}")
        lines.append("\\subsection{%s}" % titulo)
        lines.append("{\\linespread{1}\\LFXcuerpotabla")
        lines.append("\\setlength{\\parskip}{0pt}\\renewcommand{\\arraystretch}{1.10}\\setlength{\\tabcolsep}{4pt}")
        lines.append("\\begin{longtable}{F{0.09} F{0.29} F{0.40} F{0.22}}")
        lines.append("\\caption[%s]{%s. Fuente: revisión del Informe 2 y versión corregida de LafroX.}\\\\[2pt]" % (titulo, titulo))
        lines.append("\\LFXtopruleoriginal \\cab{N.º} & \\cab{Observación} & \\cab{Respuesta} & \\cab{Sección modificada} \\\\ \\midrule")
        lines.append("\\endfirsthead")
        lines.append("\\multicolumn{4}{@{}l@{}}{\\fontsize{9pt}{11pt}\\selectfont\\color{lafroxGris}Tabla \\thetable\\ (continuación)}\\\\[3pt]")
        lines.append("\\LFXtopruleoriginal \\cab{N.º} & \\cab{Observación} & \\cab{Respuesta} & \\cab{Sección modificada} \\\\ \\midrule")
        lines.append("\\endhead")
        lines.append("\\midrule")
        lines.append("\\multicolumn{4}{@{}r@{}}{\\fontsize{9pt}{11pt}\\selectfont\\color{lafroxGris}Continúa en el folio siguiente.}\\\\")
        lines.append("\\endfoot")
        lines.append("\\bottomrule")
        lines.append("\\endlastfoot")
        for i, (obs, est, resp, sec) in enumerate(filas, 1):
            if est != C and "Propuesta Final" not in resp:
                resp = resp + (" Lo que falta se completa para la Propuesta Final." if est == P else " Se corrige para la Propuesta Final.")
            rid = "%s-%02d" % (pref, i)
            sep = "\\\\" if i == len(filas) else "\\\\\n\\LFXfiletefila"
            lines.append("\\mbox{%s} & %s & \\textbf{%s.} %s & %s %s" % (rid, esc(obs), est, esc(resp), esc(sec), sep))
        lines.append("\\end{longtable}")
        lines.append("}")
        lines.append("")
    # tabla resumen
    res = ["\\begin{tablalafrox}{Síntesis del estado de las observaciones por subdocumento. Fuente: Tablas 2 a 13 de este anexo.}{tab:sintesis}{L{6.2cm} C{1.9cm} C{1.6cm} C{1.9cm} C{1.4cm}}",
           "  {\\cab{Subdocumento} & \\cab{Corregidas} & \\cab{Parciales} & \\cab{Pendientes} & \\cab{Total}}"]
    for titulo, pref, filas in GRUPOS:
        c = Counter(f[1] for f in filas)
        res.append("  %s & %d & %d & %d & %d \\\\" % (titulo.split(":")[0], c[C], c[P], c[N], len(filas)))
    T = sum(tot.values())
    res.append("  \\textbf{Total} & \\textbf{%d} & \\textbf{%d} & \\textbf{%d} & \\textbf{%d} \\\\" % (tot[C], tot[P], tot[N], T))
    res.append("\\end{tablalafrox}")
    with open(out, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    with open(out.replace(".tex", "_sintesis.tex"), "w", encoding="utf-8") as f:
        f.write("\n".join(res))
    print(tot, T)

